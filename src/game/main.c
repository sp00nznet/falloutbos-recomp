/**
 * Fallout: Brotherhood of Steel (Xbox) - recompiled game entry point
 *
 * Hosts the recompiled default.xbe. Boot order is the one every title in this
 * family uses, and it matters:
 *
 *   1. load the XBE                (the generated code reads its own .rdata and
 *                                   .data out of the mapped image)
 *   2. map the Xbox memory layout  at the original virtual addresses
 *   3. bring up the MCPX APU       DirectSound spins on the audio DSP; on
 *                                   Wreckless the whole engine init sat behind
 *                                   DirectSoundCreate succeeding
 *   4. USB host controllers        before the kernel, so XAPI finds them
 *   5. kernel replacement + thunk table
 *   6. guest stack pointer, then the recompiled entry point
 *
 * XBE details (retail, built 2003-10-02):
 *   Title:       Fallout Brotherhood of Steel
 *   Title ID:    0x49500008 (Interplay)
 *   Base addr:   0x00010000
 *   Entry point: 0x0009547C
 *   Code size:   596 KB (.text), plus D3D/DSOUND/XPP and the BINK* sections
 *   Sections:    28, XDK 1.0.5558, plain D3D8 (not D3D8LTCG)
 *   Kernel imports: 122
 *   Debug path:  z:\code\Release\FalloutXbox.exe
 *
 * This file starts as the Half-Life 2 port's main.c with the HL2-specific
 * addresses taken out. Diagnostics that belong to every title live in the
 * toolkit (RECOMP_WATCHDOG_SECS, RECOMP_FB_DUMP, RECOMP_PB_EXEC); what stays
 * here is only what needs this image's addresses.
 */

#include <windows.h>
